/** A counted noun: its forms for 1, for 2, after 3-10, after 11-99, and after round hundreds. */
function counted(
  count: number,
  one: string,
  two: string,
  few: string,
  many: string,
  hundreds: string = many
): string {
  if (count === 1) return one
  if (count === 2) return two
  const rest = count % 100
  if (count === 0 || (rest >= 3 && rest <= 10)) return `${count} ${few}`
  return `${count} ${rest >= 11 ? many : hundreds}`
}

